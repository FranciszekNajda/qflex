"""
gem5 profile for qflex (enabled with --gem5).

QFlex snapshots taken with --gem5 can be converted into gem5 checkpoints
(QPoints/scripts/convert.py). For that, the QEMU machine must only contain
what gem5's restore platform (QPoints/gem5/configs/example/arm/qflex_system.py)
can rebuild. This file is the single place where those choices are made:

  * CPU      : "max" with the ID-register overrides that make QEMU report
               the features gem5 implements, without pointer
               authentication, without PMU (gem5's platform has none).
  * GIC      : GICv3. The ITS is kept (Linux panics at boot without it),
               but stays unused: the legacy virtio-pci disk uses INTx wires
               and there is no NIC, so no device sends MSIs/LPIs.
  * Disk     : legacy virtio-blk-pci (gem5's PciVirtIO only implements the
               legacy interface), with every optional feature that gem5's
               VirtIOBlock does not implement turned off.
  * Network  : none (gem5's platform has no NIC).

qflex.args is never modified: these values replace the ones read from it,
in memory, for the duration of the command. Every value that is replaced is
printed, so the user can see what --gem5 changed.

Every step that runs QEMU on the same image (boot, load, init-warm,
functional warming, ...) must use --gem5, because QEMU only loads a snapshot
on an identical machine. A marker file next to the image records that the
image was booted with --gem5; check_marker() refuses to mix the two modes.
"""
import os

# Bump this when the profile changes in a way that makes old snapshots
# incompatible (e.g. a new device property). check_marker() then refuses
# snapshots taken with an older profile.
PROFILE_VERSION = 1

_REPO_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))

# ID-register overrides generated by QPoints/cpu_model_features/gen_id_cfg.py.
ID_OVERRIDES = os.path.join(_REPO_ROOT, "QPoints", "cpu_model_features",
                            "gem5-allrelease.cfg")

CPU_MODEL = f"max,pauth=off,pmu=off,id-overrides={ID_OVERRIDES}"

NETWORK = "none"

# Same as the default machine (commands/qemu.py), except:
#   gic-version=3 : explicit, convert.py only accepts a GICv3 (revision 3).
# The ITS is kept: Linux panics early when booted without it ("Attempted to
# kill the idle task", tested with its=off). No device sends MSIs (the disk
# has vectors=0 and there is no NIC), so the ITS stays unused and gem5's
# restore needs none; convert.py checks that no LPI is pending.
MACHINE = "virt,gic-version=3,virtualization=off,secure=off"

# Legacy virtio-blk-pci, matching gem5's PciVirtIO + VirtIOBlock:
#   disable-legacy=off,disable-modern=on : legacy interface only (I/O BAR0);
#   vectors=0         : no MSI-X, interrupts on the INTx wire;
#   num-queues=1      : gem5's VirtIOBlock has a single request queue;
#   queue-size=128    : gem5's default queueSize;
#   indirect_desc, event_idx, discard, write-zeroes, config-wce : features
#                       gem5 does not implement, so the guest must not
#                       negotiate them.
DISK_DEVICE = ("virtio-blk-pci,drive=hd0,"
               "disable-legacy=off,disable-modern=on,vectors=0,"
               "num-queues=1,queue-size=128,"
               "indirect_desc=off,event_idx=off,"
               "discard=off,write-zeroes=off,config-wce=off")


def _replace(name, old, new):
    """Return new, printing it when it differs from the value of qflex.args."""
    if old != new:
        print(f"[gem5 profile] --{name}: {old} -> {new}")
    return new


def apply(cpu_model: str, network: str) -> tuple[str, str]:
    """Replace the qflex.args choices that gem5 constrains."""
    if not os.path.isfile(ID_OVERRIDES):
        raise FileNotFoundError(
            f"--gem5: ID-register overrides not found at {ID_OVERRIDES}")
    cpu_model = _replace("cpu-model", cpu_model, CPU_MODEL)
    network = _replace("network", network, NETWORK)
    return cpu_model, network


def machine_args(gem5: bool, default: str) -> str:
    """Value of QEMU's -M option."""
    return MACHINE if gem5 else default


def disk_interface(gem5: bool) -> str:
    """
    First options of QEMU's -drive. The callers add file=, format= and their
    own options (e.g. snapshot=on in run_flexus.sh.j2).

    Default: if=virtio, which lets QEMU pick the disk device.
    gem5   : if=none, the device is created by disk_device().
    """
    return "if=none,id=hd0" if gem5 else "if=virtio"


def disk_device(gem5: bool) -> str:
    """QEMU option that creates the disk device ('' by default)."""
    return f"-device {DISK_DEVICE}" if gem5 else ""


def check_marker(gem5: bool, image_address: str, is_boot: bool) -> None:
    """
    Refuse to mix --gem5 and non --gem5 steps on the same image.

    The marker <image>.gem5 holds PROFILE_VERSION. It is written by the
    boot step run with --gem5; every other step checks it.
    """
    marker = f"{image_address}.gem5"
    exists = os.path.isfile(marker)

    if gem5 and is_boot:
        with open(marker, "w") as f:
            f.write(f"{PROFILE_VERSION}\n")
        return
    if not gem5 and exists:
        raise ValueError(
            f"{image_address} was booted with --gem5 ({marker} exists): "
            f"add --gem5 to this command.")
    if gem5 and not exists:
        raise ValueError(
            f"{image_address} was not booted with --gem5 ({marker} is "
            f"missing): run this command without --gem5, or boot again "
            f"with --gem5.")
    if gem5:
        with open(marker) as f:
            version = int(f.read().strip())
        if version != PROFILE_VERSION:
            raise ValueError(
                f"{image_address} was booted with gem5 profile "
                f"v{version}, this qflex uses v{PROFILE_VERSION}: "
                f"boot again with --gem5.")